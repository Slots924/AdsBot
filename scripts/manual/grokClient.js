async function testGrokClient() {
    if (!prompt.trim()) {
        console.log(
            "Запит не виконано: заповніть prompt на початку файла."
        );
        return;
    }

    const systemPrompt = await loadGrokSystemPrompt();
    const grokClient = new GrokClient();
    const result = await grokClient.generateText({
        systemPrompt,
        prompt,
    });

    console.log("\n=== ВІДПОВІДЬ GROK ===\n");
    console.log(result.text);
    console.log("\n=== МЕТАДАНІ ===\n");
    console.table([{
        responseId: result.responseId,
        model: result.model,
        inputTokens: result.usage?.input_tokens ?? "—",
        outputTokens: result.usage?.output_tokens ?? "—",
        totalTokens: result.usage?.total_tokens ?? "—",
    }]);
}


testGrokClient().catch((error) => {
    console.error("Помилка Grok:");
    console.table([{
        message: error.message,
        code: error.code ?? "—",
        httpStatus: error.httpStatus ?? "—",
        apiCode: error.apiCode ?? "—",
        apiType: error.apiType ?? "—",
    }]);
    process.exitCode = 1;
});
